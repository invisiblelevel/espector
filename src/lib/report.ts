export function buildMarkdownReport(
  result: ScanResult,
  locale: Locale,
  _dict: Dict,
): string {
  const s = REPORT_STRINGS[locale];
  const lines: string[] = [];

  lines.push(`# ${s.title}`);
  lines.push("");

  lines.push(`- **${s.scannedFolder}:** \`${result.rootPath}\``);
  lines.push(`- **${s.files}:** ${result.files.length}`);
  lines.push(`- **${s.plugins}:** ${result.plugins.length}`);
  lines.push(`- **${s.keys}:** ${result.totalKeys}`);
  lines.push(`- **${s.conflicts}:** ${result.conflictCount}`);
  lines.push("");

  if (result.conflicts.length === 0) {
    lines.push(s.noConflicts);
    lines.push("");
  } else {
    const sorted = [...result.conflicts].sort((a, b) => {
      if (a.valuesDiffer !== b.valuesDiffer) return a.valuesDiffer ? -1 : 1;
      return a.fullKey.localeCompare(b.fullKey);
    });

    for (const conflict of sorted) {
      lines.push(...formatConflict(conflict, s));
      lines.push("");
    }
  }

  lines.push(`## ${s.pluginsSection}`);
  lines.push("");

  if (result.plugins.length === 0) {
    lines.push(s.noPlugins);
    lines.push("");
  } else {
    lines.push(...formatPluginsTable(result.plugins, s));
    lines.push("");

    for (const plugin of result.plugins) {
      lines.push(...formatPluginDetail(plugin, s));
      lines.push("");
    }
  }

  lines.push("---");
  lines.push("");
  lines.push(`*${s.generatedBy}*`);
  lines.push("");
  lines.push(`> ${s.alphabeticalNote}`);
  lines.push("");

  return lines.join("\n");
}

function formatConflict(c: ConflictGroup, s: ReportStrings): string[] {
  const out: string[] = [];

  out.push(`## \`[${c.section}]\` ${c.key}`);
  out.push("");

  const meta: string[] = [];
  if (c.valuesDiffer) {
    meta.push(`**${c.uniqueValuesCount}** ${s.uniqueValues}`);
  } else {
    meta.push(s.identicalValues);
  }
  if (c.winner) {
    meta.push(
      `**${s.winner}:** \`${c.winner.fileRelativePath}\` = \`${c.winner.value}\``,
    );
  }
  out.push(`> ${meta.join(" · ")}`);
  out.push("");

  out.push(`| ${s.tableFile} | ${s.tableValue} | ${s.tableLine} |`);
  out.push("| --- | --- | --- |");
  for (const occ of c.occurrences) {
    const file = occ.fileRelativePath.replace(/\|/g, "\\|");
    const value = occ.value.replace(/\|/g, "\\|");
    out.push(`| \`${file}\` | \`${value}\` | ${occ.line} |`);
  }

  return out;
}

function formatPluginsTable(plugins: PluginFile[], s: ReportStrings): string[] {
  const out: string[] = [];
  out.push(
    `| ${s.pluginTable.name} | ${s.pluginTable.kind} | ${s.pluginTable.records} | ${s.pluginTable.masters} |`,
  );
  out.push("| --- | --- | --- | --- |");
  for (const p of plugins) {
    const name = p.name.replace(/\|/g, "\\|");
    out.push(
      `| \`${name}\` | ${p.kind.toUpperCase()} | ${p.totalRecords} | ${p.header.masters.length} |`,
    );
  }
  return out;
}

function formatPluginDetail(p: PluginFile, s: ReportStrings): string[] {
  const out: string[] = [];

  out.push(`### \`${p.name}\``);
  out.push("");

  const meta: string[] = [];
  meta.push(`**${s.pluginTable.kind}:** ${p.kind.toUpperCase()}`);
  meta.push(`**${s.pluginTable.records}:** ${p.totalRecords}`);
  if (p.header.author) {
    meta.push(`**${s.pluginTable.author}:** ${p.header.author}`);
  }
  if (p.header.version > 0) {
    meta.push(`**${s.pluginTable.version}:** ${p.header.version.toFixed(2)}`);
  }
  out.push(meta.join(" · "));
  out.push("");

  if (p.header.masters.length > 0) {
    out.push(`**${s.pluginTable.masters}:**`);
    out.push("");
    for (const m of p.header.masters) {
      out.push(`- \`${m}\``);
    }
    out.push("");
  }

  if (p.recordCounts.length > 0) {
    out.push(`**${s.recordTypes}:**`);
    out.push("");
    const sorted = [...p.recordCounts].sort((a, b) => b.count - a.count);
    for (const rec of sorted) {
      out.push(`- \`${rec.recordType}\`: ${rec.count}`);
    }
  }

  return out;
}

