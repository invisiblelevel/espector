/// Собирает Markdown-отчёт из результата сканирования.
export function buildMarkdownReport(
  result: ScanResult,
  locale: Locale,
  _dict: Dict,
): string {
  const s = REPORT_STRINGS[locale];
  const lines: string[] = [];

  // Заголовок.
  lines.push(`# ${s.title}`);
  lines.push("");

  // Сводка.
  lines.push(`- **${s.scannedFolder}:** \`${result.rootPath}\``);
  lines.push(`- **${s.files}:** ${result.files.length}`);
  lines.push(`- **${s.keys}:** ${result.totalKeys}`);
  lines.push(`- **${s.conflicts}:** ${result.conflictCount}`);
  lines.push("");

  if (result.conflicts.length === 0) {
    lines.push(s.noConflicts);
    lines.push("");
  } else {
    // Сортируем так же, как в UI: разные значения — наверх.
    const sorted = [...result.conflicts].sort((a, b) => {
      if (a.valuesDiffer !== b.valuesDiffer) return a.valuesDiffer ? -1 : 1;
      return a.fullKey.localeCompare(b.fullKey);
    });

    for (const conflict of sorted) {
      lines.push(...formatConflict(conflict, s));
      lines.push("");
    }
  }

  // Подвал.
  lines.push("---");
  lines.push("");
  lines.push(`*${s.generatedBy}*`);
  lines.push("");
  lines.push(`> ${s.alphabeticalNote}`);
  lines.push("");

  return lines.join("\n");
}

/// Форматирует один конфликт в блок Markdown.
function formatConflict(c: ConflictGroup, s: ReportStrings): string[] {
  const out: string[] = [];

  // Заголовок конфликта: `[Section] key`
  out.push(`## \`[${c.section}]\` ${c.key}`);
  out.push("");

  // Мета: уникальные значения, победитель.
  const meta: string[] = [];
  if (c.valuesDiffer) {
    meta.push(`**${c.uniqueValuesCount}** ${s.uniqueValues}`);
  } else {
    meta.push(s.identicalValues);
  }
  if (c.winner) {
    meta.push(
      `**${s.winner}:** \`${c.winner.fileRelativePath}\` = \`${c.winner.value}\``,
    );
  }
  out.push(`> ${meta.join(" · ")}`);
  out.push("");

  // Таблица со всеми вхождениями.
  out.push(`| ${s.tableFile} | ${s.tableValue} | ${s.tableLine} |`);
  out.push("| --- | --- | --- |");
  for (const occ of c.occurrences) {
    // Экранируем пайпы, чтобы не разломать таблицу.
    const file = occ.fileRelativePath.replace(/\|/g, "\\|");
    const value = occ.value.replace(/\|/g, "\\|");
    out.push(`| \`${file}\` | \`${value}\` | ${occ.line} |`);
  }

  return out;
}