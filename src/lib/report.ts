/// Экранирует CSV-поле: оборачивает в кавычки, если есть запятые/кавычки/переносы.
function csvEscape(value: string): string {
  if (
    value.includes(",") ||
    value.includes('"') ||
    value.includes("\n") ||
    value.includes("\r")
  ) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

/// Собирает CSV-отчёт. Раздел INI-конфликтов — основная таблица.
/// Формат: Section, Key, File, Value, Line, IsWinner, UniqueValues, ValuesDiffer
export function buildCsvReport(result: ScanResult, _locale: Locale): string {
  const lines: string[] = [];

  // Заголовок.
  lines.push(
    [
      "section",
      "key",
      "file",
      "value",
      "line",
      "is_winner",
      "unique_values",
      "values_differ",
    ].join(","),
  );

  const sorted = [...result.conflicts].sort((a, b) =>
    a.fullKey.localeCompare(b.fullKey),
  );

  for (const conflict of sorted) {
    for (const occ of conflict.occurrences) {
      const isWinner = occ.filePath === conflict.winner.filePath ? "1" : "0";
      lines.push(
        [
          csvEscape(conflict.section),
          csvEscape(conflict.key),
          csvEscape(occ.fileRelativePath),
          csvEscape(occ.value),
          String(occ.line),
          isWinner,
          String(conflict.uniqueValuesCount),
          conflict.valuesDiffer ? "1" : "0",
        ].join(","),
      );
    }
  }

  return lines.join("\n");
}