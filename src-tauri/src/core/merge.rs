//! Генератор merged.ini: собирает все ключи из всех файлов скана
//! в один файл, разрешая конфликты по победителю (последний по алфавиту).
//!
//! Логика:
//! - Идём по всем файлам скана.
//! - Для каждого ключа (Section.Key) запоминаем вхождение и файл.
//! - Если ключ конфликтный — берём значение победителя.
//! - Если неконфликтный — берём как есть.
//! - Секции сортируются по алфавиту для стабильного вывода.
//! - Перед каждым ключом — комментарий с источником.

use crate::models::ScanResult;
use std::collections::BTreeMap;

/// Собирает merged.ini из результата сканирования.
/// Возвращает готовый текст файла.
pub fn build_merged_ini(result: &ScanResult) -> String {
    // Карта: имя секции -> список ключей в этой секции.
    // BTreeMap даёт стабильный алфавитный порядок секций.
    let mut sections: BTreeMap<String, Vec<MergedKey>> = BTreeMap::new();

    // 1. Собираем победителей по конфликтным ключам.
    //    Ключ карты: "Section.Key", значение: (value, file_relative_path, line).
    let mut winners: BTreeMap<String, (String, String, usize)> = BTreeMap::new();
    for conflict in &result.conflicts {
        winners.insert(
            conflict.full_key.clone(),
            (
                conflict.winner.value.clone(),
                conflict.winner.file_relative_path.clone(),
                0, // line победителя достанем отдельно из occurrences
            ),
        );
    }

    // Дополняем winners line-номером: ищем вхождение в occurrences,
    // которое совпадает с победителем.
    for conflict in &result.conflicts {
        if let Some(occ) = conflict
            .occurrences
            .iter()
            .find(|o| o.file_path == conflict.winner.file_path)
        {
            if let Some(w) = winners.get_mut(&conflict.full_key) {
                w.2 = occ.line;
            }
        }
    }

    // 2. Идём по всем файлам в порядке relative_path (как они грузятся).
    //    Для каждого ключа решаем: писать или пропустить.
    for file in &result.files {
        for section in &file.sections {
            for key in &section.keys {
                let full = format!("{}.{}", section.name, key.name);

                // Если ключ конфликтный и текущий файл НЕ победитель — пропускаем.
                if let Some(w) = winners.get(&full) {
                    if w.1 != file.relative_path {
                        continue;
                    }
                }

                // Добавляем ключ в секцию.
                let entry = sections.entry(section.name.clone()).or_default();

                // Защита от дублей: если ключ уже добавлен (например,
                // один файл дважды содержит его) — пропускаем.
                if entry.iter().any(|k| k.name == key.name) {
                    continue;
                }

                entry.push(MergedKey {
                    name: key.name.clone(),
                    value: key.value.clone(),
                    source_file: file.relative_path.clone(),
                    source_line: key.line,
                });
            }
        }
    }

    // 3. Формируем текст файла.
    let mut out = String::new();

    // Заголовок.
    out.push_str("; ============================================================\n");
    out.push_str("; merged.ini — generated by ESPector\n");
    out.push_str("; ------------------------------------------------------------\n");
    out.push_str(&format!("; Source folder: {}\n", result.root_path));
    out.push_str(&format!("; Files scanned: {}\n", result.files.len()));
    out.push_str(&format!("; Total keys: {}\n", result.total_keys));
    out.push_str(&format!("; Conflicts resolved: {}\n", result.conflict_count));
    out.push_str("; ------------------------------------------------------------\n");
    out.push_str("; Conflicting keys use the value from the winner (last file\n");
    out.push_str("; in alphabetical order — same as loose .ini load order).\n");
    out.push_str("; Each key has a comment with its source file and line.\n");
    out.push_str("; ============================================================\n");
    out.push('\n');

    // Секции.
    for (section_name, keys) in &sections {
        if keys.is_empty() {
            continue;
        }

        out.push_str(&format!("[{}]\n", section_name));

        for key in keys {
            out.push_str(&format!(
                "; from {}:{}\n",
                key.source_file, key.source_line
            ));
            out.push_str(&format!("{}={}\n", key.name, key.value));
        }

        out.push('\n');
    }

    out
}

/// Один ключ в merged-файле с источником.
struct MergedKey {
    name: String,
    value: String,
    source_file: String,
    source_line: usize,
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::*;

    fn make_key(name: &str, value: &str, line: usize) -> IniKey {
        IniKey {
            name: name.to_string(),
            value: value.to_string(),
            line,
            inline_comment: None,
        }
    }

    fn make_file(rel: &str, sections: Vec<IniSection>) -> IniFile {
        IniFile {
            path: format!("/test/{}", rel),
            relative_path: rel.to_string(),
            name: rel.to_string(),
            size: 0,
            sections,
            conflicting_keys: vec![],
        }
    }

    #[test]
    fn merges_non_conflicting_keys() {
        let result = ScanResult {
            root_path: "/test".to_string(),
            files: vec![make_file(
                "a.ini",
                vec![IniSection {
                    name: "Combat".to_string(),
                    keys: vec![make_key("fDamage", "1.0", 2)],
                    comments: vec![],
                }],
            )],
            conflicts: vec![],
            total_keys: 1,
            conflict_count: 0,
        };

        let out = build_merged_ini(&result);
        assert!(out.contains("[Combat]"));
        assert!(out.contains("; from a.ini:2"));
        assert!(out.contains("fDamage=1.0"));
    }

    #[test]
    fn uses_winner_for_conflicts() {
        let result = ScanResult {
            root_path: "/test".to_string(),
            files: vec![
                make_file(
                    "a.ini",
                    vec![IniSection {
                        name: "Combat".to_string(),
                        keys: vec![make_key("fDamage", "1.0", 2)],
                        comments: vec![],
                    }],
                ),
                make_file(
                    "z.ini",
                    vec![IniSection {
                        name: "Combat".to_string(),
                        keys: vec![make_key("fDamage", "5.0", 3)],
                        comments: vec![],
                    }],
                ),
            ],
            conflicts: vec![ConflictGroup {
                full_key: "Combat.fDamage".to_string(),
                section: "Combat".to_string(),
                key: "fDamage".to_string(),
                occurrences: vec![
                    ConflictOccurrence {
                        file_relative_path: "a.ini".to_string(),
                        file_path: "/test/a.ini".to_string(),
                        value: "1.0".to_string(),
                        line: 2,
                    },
                    ConflictOccurrence {
                        file_relative_path: "z.ini".to_string(),
                        file_path: "/test/z.ini".to_string(),
                        value: "5.0".to_string(),
                        line: 3,
                    },
                ],
                values_differ: true,
                unique_values_count: 2,
                winner: ConflictWinner {
                    file_relative_path: "z.ini".to_string(),
                    file_path: "/test/z.ini".to_string(),
                    value: "5.0".to_string(),
                },
            }],
            total_keys: 2,
            conflict_count: 1,
        };

        let out = build_merged_ini(&result);
        assert!(out.contains("; from z.ini:3"));
        assert!(out.contains("fDamage=5.0"));
        // a.ini не должен попасть в merged — z.ini победил.
        assert!(!out.contains("; from a.ini:2"));
    }
}